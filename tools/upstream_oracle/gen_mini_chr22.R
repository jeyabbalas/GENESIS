  rows = snp_order_block(fits2[[1]]$L, ld1$slice),
  fits = lapply(fits2, function(f) f$g),
  fit_alt_ld_w0.5MB_r0.2 = c(alt$g, list(rows_n_tagging_in_gwas = snp_order_block(alt$L, ld2$slice)$n_tagging_in_gwas)))
