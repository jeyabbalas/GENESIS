# ---- 3. genuine upstream fits -------------------------------------------------
run_fit <- function(comp, startingpic, ld_name = "LDwindow1MB_cutoff0.1", ld_slice = ld1$slice, LDwindow = 1, LDcutoff = 0.1, n_scan) {
  label <- sprintf("m%d_startingpic%s_w%sMB_r%s", comp, if (is.na(startingpic)) "NA" else format(startingpic), format(LDwindow), format(LDcutoff))
  .oracle_msg("fit ", label)
  clear_data_overrides(up); set_data_override(up, ld_name, list(dataLD = ld_slice))
  ga <- list(h22, filter = FALSE, modelcomponents = comp, cores = NT, LDcutoff = LDcutoff, LDwindow = LDwindow,
             M = M_DEFAULT, c0 = 10, BIC.gamma = 0.5, print = TRUE, printfreq = 1, starting = NA,
             startingpic = startingpic, tolerance = NA, qqplot = FALSE, stratification = TRUE)
  t0 <- Sys.time()
  cap <- call_with_locals(up, "genesis", ga)
  wall <- as.numeric(difftime(Sys.time(), t0, units = "secs"))
  L <- cap$locals
  g <- genesis_locals_to_list(cap, per_snp = "head", n_head = 200, keep_snp_order = FALSE)
  # the raw printed lines are dropped (the parsed 6-digit matrix is kept)
  g$printed_trace <- NULL
  g$label <- label
  g$wall_seconds <- wall
  g$n_em_iterations <- num(L$fit)[1] + 1
  g$n_em_iterations_note <- "fit[1] + 1 = number of completed EM iterations (E-steps) of the final fit; equals the number of printed trace rows unless the loop ended through the c0 >= 20 break"
  g$call <- list(summarydata = "height_chr22.sumstats.tsv.gz", filter = FALSE, modelcomponents = comp, cores = NT,
                 LDcutoff = LDcutoff, LDwindow = LDwindow, M = M_DEFAULT, c0 = 10, BIC.gamma = 0.5,
                 startingpic = if (is.na(startingpic)) "NA" else startingpic, starting = "NA", tolerance = "NA",
                 stratification = TRUE, qqplot = FALSE)
  d <- list(betahat = num(L$betahat), varbetahat = num(L$varbetahat), ldscore = num(L$ldscore), Nstar = num(L$Nstar))
  tol <- g$tolerances
  # starting values / preliminary 2-component fit, replicated from genesis.R and checked against the genuine run
  st2 <- ldsc_start_m2(up, d$betahat, d$varbetahat, d$ldscore, d$Nstar, M_DEFAULT, 10, startingpic, NT)
  g$ldsc <- list(intercept = st2$ldsc_intercept, slope = st2$ldsc_slope, m2_start = st2$starting, llk_at_m2_start = num(st2$llk_at_start))
  if (comp == 2) {
    g$ldsc$m2_start_identical_to_genesis_starting <- identical(st2$starting, g$starting)
  } else {
    r2 <- num(quiet(up$EM_func(st2$starting, d$betahat, d$varbetahat, d$ldscore, d$Nstar, M_DEFAULT, 10, max(tol$pic, 1e-6),
                               max(tol$sigsq1, 1e-7), max(tol$a, 1e-7), max(tol$llk, 1e-5), tol$maxEM, tol$steps, NT, FALSE, 1, TRUE)))
    e2 <- r2[3:5]; rebuilt <- c(e2[1], 1.0/9, e2[2] * 5, (e2[2] * 5) / 10, e2[3])
    g$prelim_m2 <- list(result = r2, tolerances = list(pic = max(tol$pic, 1e-6), sigsq1 = max(tol$sigsq1, 1e-7), a = max(tol$a, 1e-7), llk = max(tol$llk, 1e-5)),
                        m3_start_rebuilt = rebuilt, rebuilt_identical_to_genesis_starting = identical(rebuilt, g$starting))
  }
  # full-precision trace of the first iterations (Meps scan)
  g$em_trace_first_iterations <- lapply(seq_len(n_scan), function(m) {
    res <- if (comp == 2)
      quiet(up$EM_func(g$starting, d$betahat, d$varbetahat, d$ldscore, d$Nstar, M_DEFAULT, 10, tol$pic, tol$sigsq1, tol$a, tol$llk, m, tol$steps, NT, FALSE, 1, TRUE))
    else
      quiet(up$EM_func3(g$starting, c(1e-7, 1e-7), c(0.5, 0.5), d$betahat, d$varbetahat, d$ldscore, d$Nstar, M_DEFAULT, 10,
                        tol$pic, tol$p1, tol$sigsq1, tol$sigsq2, tol$a, tol$llk, m, tol$steps, NT, FALSE, 1, TRUE))
    list(Meps = m, result = num(res))
  })
  est <- g$est; c0f <- g$c0_final
  # deterministic downstream functions at the fitted values
  pm <- up$postmarginal(L$df, est, c0 = c0f)
  g$postmarginal_first200 <- list(c0_used = c0f, snp = as.character(pm$snp[1:200]), prob_beta0 = num(pm$prob.beta0[1:200]),
                                  posteriormean_marginal = num(pm$posteriormean.marginal[1:200]))
  g$postmarginal_sums <- list(sum_prob_beta0 = sum(pm$prob.beta0), sum_abs_posteriormean = sum(abs(pm$posteriormean.marginal)))
  g$projection_n253288 <- up$projection(est, v = NULL, n = 253288, CI = FALSE)
  g$numInterval_0.005_Inf <- num(up$numInterval(0.005, Inf, est))
  g$function_values_at_est <- if (comp == 2) list(
      loglikelihood_c0_final = num(up$loglikelihood(est, d$betahat, d$varbetahat, d$ldscore, c0f, d$Nstar, NT)),
      loglikelihood_c0_10 = num(up$loglikelihood(est, d$betahat, d$varbetahat, d$ldscore, 10, d$Nstar, NT)),
      S = num(up$S(est, d$betahat, d$varbetahat, d$ldscore, c0f, d$Nstar, NT)))
    else list(
      loglikelihood3_c0_final = num(up$loglikelihood3(est, d$betahat, d$varbetahat, d$ldscore, c0f, d$Nstar, NT)),
      loglikelihood3_c0_10 = num(up$loglikelihood3(est, d$betahat, d$varbetahat, d$ldscore, 10, d$Nstar, NT)))
  list(g = g, L = L, cap = cap)
}

snp_order_block <- function(L, ld_slice) {
  snp <- as.character(L$SNP)
  tags <- strsplit(as.character(L$TaggingSNPs), ",")
  ntag_in <- vapply(tags, function(t) sum(t %in% snp), 1L)
  list(snp_order = snp, K = length(snp),
       snp_order_note = "row order of upstream's merged data frame = order of the summary-statistics rows (base::merge, sort = FALSE)",
       n_tagging_in_gwas = ntag_in,
       n_tagging_in_gwas_note = "per row: how many SNPs of its tagging list (self included) are present in the GWAS; these are the terms of upstream's neighbourhood score sum BEFORE it adds the SNP's own score once more",
       checksums = list(sum_betahat = sum(num(L$betahat)), sum_varbetahat = sum(num(L$varbetahat)),
                        sum_ldscore = sum(num(L$ldscore)), sum_Nstar = sum(num(L$Nstar)), mean_n = mean(L$n),
                        max_rs_number = max(L$inx_name), dictionary_length = length(L$dictionary)),
       first_rows = list(SNP = snp[1:5], betahat = num(L$betahat)[1:5], varbetahat = num(L$varbetahat)[1:5],
                         ldscore = num(L$ldscore)[1:5], Nstar = num(L$Nstar)[1:5]))
}

fits2 <- list(run_fit(2, NA, n_scan = 30L), run_fit(2, 0.005, n_scan = 30L))
