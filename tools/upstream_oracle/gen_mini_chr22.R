#!/usr/bin/env Rscript
# gen_mini_chr22.R -- real-data mini pipeline: chromosome 22 of upstream's
# bundled LD reference + the chr22 part of the bundled height GWAS.
#
# Usage:
#   Rscript --vanilla gen_mini_chr22.R <tools_dir> <upstream_dir> <work_dir> <data_out_dir> <fixture_out_dir> [qq_nsim=100]
#
# Writes
#   <data_out_dir>/ld_w1MB_r0.1.tsv.gz, ld_w0.5MB_r0.2.tsv.gz   chr22 slices of upstream's dataLD tables
#   <data_out_dir>/height_chr22.sumstats.tsv.gz                 SNP, Z, N
#   <data_out_dir>/README.md
#   <fixture_out_dir>/mini_chr22_m2.json.gz, mini_chr22_m3.json.gz, mini_chr22_stochastic.json
# The fits are produced by the genuine upstream genesis() (see lib/build_upstream.R).

args <- commandArgs(trailingOnly = TRUE)
if (length(args) < 5) stop("usage: gen_mini_chr22.R <tools_dir> <upstream_dir> <work_dir> <data_out_dir> <fixture_out_dir> [qq_nsim]")
tools <- args[1]; upstream <- args[2]; work <- args[3]; data_out <- args[4]; fx_out <- args[5]
qq_nsim <- if (length(args) >= 6) as.integer(args[6]) else 100L
.libPaths(c(file.path(work, "rlib"), .libPaths()))
source(file.path(tools, "lib", "build_upstream.R"))
source(file.path(tools, "lib", "oracle_utils.R"))
up <- build_upstream(upstream, work, tools, openmp = "auto")
dir.create(data_out, recursive = TRUE, showWarnings = FALSE)
NT <- 1L
M_DEFAULT <- 1070777

write_tsv_gz <- function(df, path) {
  con <- gzfile(path, open = "wb", compression = 9)
  write.table(df, con, sep = "\t", quote = FALSE, row.names = FALSE, col.names = TRUE)
  close(con)   # before measuring the size
  .oracle_msg(sprintf("wrote %s (%.1f kB)", path, file.info(path)$size / 1024))
}
g17 <- function(x) sprintf("%.17g", x)

# ---- 1. chr22 slices of the LD tables ----------------------------------------
slice_ld <- function(name, out_name) {
  e <- new.env(); load(file.path(upstream, "data", paste0(name, ".RData")), envir = e)
  d <- e$dataLD
  s <- d[d$CHR == 22, ]
  tags <- strsplit(as.character(s$TaggingSNPs), ",")
  closed <- all(unlist(tags) %in% as.character(s$SNPname))
  self <- all(mapply(function(a, b) a %in% b, as.character(s$SNPname), tags))
  out <- data.frame(SNP = as.character(s$SNPname), CHR = s$CHR, BP = s$BP, Nstar = s$Nstar,
                    LD.score.correct = g17(s$LD.score.correct), TaggingSNPs = as.character(s$TaggingSNPs),
                    stringsAsFactors = FALSE)
  write_tsv_gz(out, file.path(data_out, out_name))
  list(slice = s, info = list(source_dataset = name, file = out_name, n_snps = nrow(s),
                              tagging_lists_closed_within_chr22 = closed, every_list_contains_self = self,
                              n_tagging_equals_Nstar = all(lengths(tags) == s$Nstar),
                              sum_Nstar = sum(s$Nstar), sum_ldscore = sum(s$LD.score.correct),
                              row_order = "as stored in upstream's dataLD (not sorted by position)"))
}
ld1 <- slice_ld("LDwindow1MB_cutoff0.1", "ld_w1MB_r0.1.tsv.gz")
ld2 <- slice_ld("LDwindow0.5MB_cutoff0.2", "ld_w0.5MB_r0.2.tsv.gz")
stopifnot(setequal(ld1$slice$SNPname, ld2$slice$SNPname))

# ---- 2. chr22 rows of the bundled height GWAS --------------------------------
e <- new.env(); load(file.path(upstream, "data", "heightGWAS.RData"), envir = e)
h <- e$heightGWAS
rows <- which(as.character(h[[1]]) %in% as.character(ld1$slice$SNPname))
h22 <- h[rows, ]                                    # still upstream's factor columns
ss_out <- data.frame(SNP = as.character(h22[[1]]), Z = as.character(h22[[2]]), N = as.character(h22[[3]]), stringsAsFactors = FALSE)
write_tsv_gz(ss_out, file.path(data_out, "height_chr22.sumstats.tsv.gz"))
# the decimal strings round-trip to the doubles upstream uses
stopifnot(identical(as.numeric(ss_out$Z), as.numeric(as.character(h22[[2]]))))

writeLines(c(
  "# mini_chr22 -- chromosome 22 slice of the upstream GENESIS reference data",
  "",
  "Generated by `tools/upstream_oracle/gen_mini_chr22.R` from the upstream repository",
  "(https://github.com/yandorazhang/GENESIS, bundled `data/*.RData`). Do not edit by hand.",
  "",
  "| file | content |",
  "|---|---|",
  sprintf("| `ld_w1MB_r0.1.tsv.gz` | the %d chr22 rows of `LDwindow1MB_cutoff0.1` (`dataLD`): `SNP`, `CHR`, `BP` (GRCh37), `Nstar`, `LD.score.correct` (17 significant digits), `TaggingSNPs` (comma-joined rsIDs exactly as upstream; the SNP itself is included) |", nrow(ld1$slice)),
  "| `ld_w0.5MB_r0.2.tsv.gz` | same SNPs from `LDwindow0.5MB_cutoff0.2` |",
  sprintf("| `height_chr22.sumstats.tsv.gz` | the %d rows of upstream's `heightGWAS` (GIANT height, Lango Allen et al. 2010) whose SNP is in the chr22 reference: `SNP`, `Z`, `N` (decimal strings exactly as stored upstream) |", nrow(ss_out)),
  "",
  "Row order is upstream's storage order in both tables (LD tables are not sorted by position;",
