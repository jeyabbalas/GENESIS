# ---- 4. stochastic: seeded single runs (R RNG; not reproducible elsewhere) ----
try_rec <- function(expr) {
  w <- character()
  v <- withCallingHandlers(
    tryCatch(list(status = "ok", value = expr), error = function(e) list(status = "error", error_message = conditionMessage(e))),
    warning = function(cond) { w <<- c(w, conditionMessage(cond)); invokeRestart("muffleWarning") })
  if (length(w)) v$warnings <- I(unique(w))
  v
}
proj_ci <- function(r) list(heritability = num(r$heritability), Numdiscoveries_est_low_high = unname(as.numeric(r$Numdiscoveries)),
                            pheno.variance_est_low_high = unname(as.numeric(r$pheno.variance)), GVpercentage_est_low_high = unname(as.numeric(r$GVpercentage)))
qq_block <- function(f, nsim) {
  L <- f$L; est <- f$g$est; c0f <- f$g$c0_final
  clear_data_overrides(up)   # qqplotdata.simu() loads the genome-wide error_iter* data sets itself
  t0 <- Sys.time()
  q <- try_rec(up$qqplotdata.simu(L$df, est, c0 = c0f, qqplotCI.coverage = 0.8, qqplot.nsim = nsim, LDcutoff = 0.1, LDwindow = 1,
                                  filter = FALSE, cores = 1, seeds = 123))
  sec <- as.numeric(difftime(Sys.time(), t0, units = "secs"))
  if (q$status != "ok") return(c(list(est = est, c0 = c0f, nsim = nsim, seconds = sec), q))
  qq <- q$value$QQdata; K <- nrow(qq)
  idx <- sort(unique(c(seq(1, K, by = 50), (K - 199):K)))
  list(est = est, c0 = c0f, nsim = nsim, seeds = 123, CI.coverage = 0.8, seconds = sec, status = "ok",
       observedlambda = num(q$value$observedlambda), meanEXPlambda = num(q$value$meanEXPlambda),
       lowEXPlambda = num(q$value$lowEXPlambda), highEXPlambda = num(q$value$highEXPlambda),
       QQdata_rows1 = idx, QQdata_note = "thinned: every 50th row plus the 200 largest; rows are sorted ascending by -log10(p); columns as upstream",
       QQdata = list(log_obs_pvalues = num(qq$log_obs_pvalues[idx]), mean_log_exp_pvalues = num(qq$mean_log_exp_pvalues[idx]),
                     lower = num(qq$lower[idx]), upper = num(qq$upper[idx])))
}
.oracle_msg("stochastic runs (qqplotdata.simu with ", qq_nsim, " simulations per model) ...")
f2 <- fits2[[1]]; f3 <- fits3[[1]]
sto <- list(
  meta = oracle_meta(up, upstream, threads = NT, extra = list(fixture = "mini chr22: seeded single runs of upstream's RNG-based functions")),
  label = "stochastic",
  note = "These depend on R's RNG stream (set.seed + sample/rnorm/mvrnorm/rbinom) and on upstream's bundled error_iter* vectors; use only for statistical sanity comparisons.",
  projection_CI_m2 = c(list(est = f2$g$est, v = f2$g$var_est, n = 253288, nsim = 1000, CI.coverage = 0.95, seeds = 123),
                       try_rec(proj_ci(up$projection(f2$g$est, f2$L$var_est, n = 253288, CI = TRUE)))),
  projection_CI_m3 = c(list(est = f3$g$est, v = f3$g$var_est, n = 253288, nsim = 1000, CI.coverage = 0.95, seeds = 123),
                       try_rec(proj_ci(up$projection(f3$g$est, f3$L$var_est, n = 253288, CI = TRUE)))),
  qqplotdata_simu_m2 = qq_block(f2, qq_nsim),
  qqplotdata_simu_m3 = qq_block(f3, qq_nsim))
write_json(sto, file.path(fx_out, "mini_chr22_stochastic.json"))
